// The rendered dashboard is valid JSON, its SLO panels query recording rules the
// PrometheusRule records, and the objective, window and RPO are filled in: the backup ages
// turn orange at one and a half schedule intervals and red at the RPO (here hourly: 2h).
func TestDashboardSLOPanels(t *testing.T) {
	f := testInstance("dash")
	f.Spec.Backup.Enabled = true
	f.Spec.Backup.Schedule = testHourlySchedule
	f.Spec.Monitoring.SLO = forgejov1.SLOSpec{AvailabilityTarget: test999, Window: test28d}
	out := renderDashboard(f)
	var d struct {
		Panels []struct {
			Title       string                  `json:"title"`
			Targets     []struct{ Expr string } `json:"targets"`
			FieldConfig struct {
				Defaults struct {
					Thresholds struct {
						Steps []struct {
							Value any `json:"value"`
						} `json:"steps"`
					} `json:"thresholds"`
				} `json:"defaults"`
			} `json:"fieldConfig"`
		} `json:"panels"`
		Templating struct {
			List []struct{ Name, Query string } `json:"list"`
		} `json:"templating"`
	}
	if err := json.Unmarshal([]byte(out), &d); err != nil {
		t.Fatalf("dashboard is not JSON: %v", err)
	}
	recorded := map[string]bool{}
	for _, g := range ruleSpecOf(t, f, true).Groups {
		for _, r := range g.Rules {
			recorded[r.Record] = true
		}
	}
	sloMetric := regexp.MustCompile(`forgejo_slo:[a-z_]+`)
	used, rpoPanels := 0, 0
	for _, p := range d.Panels {
		for _, tg := range p.Targets {
			for _, m := range sloMetric.FindAllString(tg.Expr, -1) {
				used++
				if !recorded[m] {
					t.Errorf("panel %q queries %s, which no rule records", p.Title, m)
				}
			}
		}
		steps := p.FieldConfig.Defaults.Thresholds.Steps
		if strings.HasPrefix(p.Title, "Availability (") {
			if v := steps[1].Value; v != 0.999 {
				t.Errorf("availability threshold %v, want the objective 0.999", v)
			}
		}
		if p.Title == "Last successful backup" || p.Title == "Recovery point age" {
			rpoPanels++
			if len(steps) != 3 || steps[1].Value != 5400.0 || steps[2].Value != 7200.0 {
				t.Errorf("%s: thresholds %+v, want orange at 5400 (1.5 intervals) and red at 7200 (the RPO)", p.Title, steps)
			}
		}
	}
	if used < 6 {
		t.Errorf("only %d SLO queries in the dashboard", used)
	}
	if rpoPanels != 2 {
		t.Errorf("%d backup age stats, want 2", rpoPanels)
	}
	window := ""
	for _, v := range d.Templating.List {
		if v.Name == "slo_window" {
			window = v.Query
		}
	}
	if left := regexp.MustCompile(`__[A-Z_]+__`).FindAllString(out, -1); window != test28d || len(left) > 0 {
		t.Errorf("slo_window %q; placeholders left: %v", window, left)
	}
}
