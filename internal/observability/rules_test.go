// The burn-rate windows follow the SRE workbook at 30 days and scale with the window, at
// least 5m and three health-check intervals (rounded up to minutes); the budget is exact for
// decimal targets.
func TestSLOWindowsAndBudget(t *testing.T) {
	h := time.Hour
	for _, tt := range []struct {
		target, window, objective, budget string
		interval                          time.Duration
		long, short                       []time.Duration
	}{
		{"", "", objective995, budget995, 0,
			[]time.Duration{time.Hour, 6 * time.Hour, 24 * time.Hour, 72 * time.Hour},
			[]time.Duration{5 * time.Minute, 30 * time.Minute, 2 * time.Hour, 6 * time.Hour}},
		{"99.95", "7d", "0.9995", "0.0005", 0,
			[]time.Duration{14 * time.Minute, 84 * time.Minute, 336 * time.Minute, 1008 * time.Minute},
			[]time.Duration{5 * time.Minute, 7 * time.Minute, 28 * time.Minute, 84 * time.Minute}},
		{test999, "1d", objective999, budget999, 0,
			[]time.Duration{5 * time.Minute, 12 * time.Minute, 48 * time.Minute, 144 * time.Minute},
			[]time.Duration{5 * time.Minute, 5 * time.Minute, 5 * time.Minute, 12 * time.Minute}},
		// 3 x 100s is exactly 5m; 3 x 110s rounds up to 6m.
		{test999, "1d", objective999, budget999, 100 * time.Second,
			[]time.Duration{5 * time.Minute, 12 * time.Minute, 48 * time.Minute, 144 * time.Minute},
			[]time.Duration{5 * time.Minute, 5 * time.Minute, 5 * time.Minute, 12 * time.Minute}},
		{test999, "1d", objective999, budget999, 110 * time.Second,
			[]time.Duration{6 * time.Minute, 12 * time.Minute, 48 * time.Minute, 144 * time.Minute},
			[]time.Duration{6 * time.Minute, 6 * time.Minute, 6 * time.Minute, 12 * time.Minute}},
		{"", "", objective995, budget995, 10 * time.Minute,
			[]time.Duration{h, 6 * h, 24 * h, 72 * h},
			[]time.Duration{30 * time.Minute, 30 * time.Minute, 2 * h, 6 * h}},
		{"", "", objective995, budget995, h,
			[]time.Duration{3 * h, 6 * h, 24 * h, 72 * h},
			[]time.Duration{3 * h, 3 * h, 3 * h, 6 * h}},
		// Bounded at a day, so that the product cannot overflow.
		{"", "", objective995, budget995, 1 << 62,
			[]time.Duration{72 * h, 72 * h, 72 * h, 72 * h},
			[]time.Duration{72 * h, 72 * h, 72 * h, 72 * h}},
	} {
		f := testInstance("slo")
		f.Spec.Monitoring.SLO = forgejov1.SLOSpec{AvailabilityTarget: tt.target, Window: tt.window}
		if tt.interval > 0 {
			f.Spec.AutoPilot.SelfHealing.HealthCheckInterval = &metav1.Duration{Duration: tt.interval}
		}
		s, err := sloOf(f)
		if err != nil {
			t.Fatal(err)
		}
		if s.objective != tt.objective || s.budget != tt.budget {
			t.Errorf("%s: objective %s budget %s", tt.target, s.objective, s.budget)
		}
		for i, b := range burnAlerts {
			if s.scaled(b.long) != tt.long[i] || s.scaled(b.short) != tt.short[i] {
				t.Errorf("%s/%s/%s pair %d: %s/%s, want %s/%s", tt.target, tt.window, tt.interval, i, s.scaled(b.long), s.scaled(b.short), tt.long[i], tt.short[i])
			}
		}
	}
	for _, bad := range []forgejov1.SLOSpec{{AvailabilityTarget: "100"}, {AvailabilityTarget: "0"}, {AvailabilityTarget: "1e2"},
		{AvailabilityTarget: "abc"}, {Window: "30m"}, {Window: "month"}} {
		f := testInstance("slo")
		f.Spec.Monitoring.SLO = bad
		if _, err := sloOf(f); err == nil {
			t.Errorf("%+v accepted", bad)
		}
	}
}

